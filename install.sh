#!/usr/bin/env bash
set -eo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="$REPO_DIR/models.env"
ZSHRC="$HOME/.zshrc"
RA_DB="$HOME/.ra/data.sql"
OMP_ENV="$HOME/.omp/.env"
MARKER="# >>> omp-mc config >>>"
MARKER_END="# <<< omp-mc config <<<"

# 1. Load User Config
if [ ! -f "$CONFIG_FILE" ]; then
    echo "⚠️  models.env not found. Creating from example..."
    cp "$REPO_DIR/models.env.example" "$CONFIG_FILE"
fi
source "$CONFIG_FILE"

echo "🔧 Installing omp-mc (MaaS Creative Distribution)..."

# 2. Sync to oh-my-pi (~/.omp/.env)
# omp プロセスが直接読み込む設定ファイルへ同期します
echo "🔄 Syncing models.env to $OMP_ENV..."
mkdir -p "$(dirname "$OMP_ENV")"
cat > "$OMP_ENV" << ENVEOF
# Generated by omp-mc install.sh - DO NOT EDIT MANUALLY
OPENCODE_API_KEY="$OPENCODE_API_KEY"
OPENCODE_KEY="$OPENCODE_API_KEY"
OPENCODE_TOKEN="$OPENCODE_API_KEY"
OPENCODE_GO_API_KEY="$OPENCODE_API_KEY"
ZENMUX_API_KEY="$OPENCODE_API_KEY"

PI_SLOW_MODEL="$PI_SLOW_MODEL"
PI_PLAN_MODEL="$PI_PLAN_MODEL"
PI_SMOL_MODEL="$PI_SMOL_MODEL"
PI_MODEL="$PI_SMOL_MODEL"
ENVEOF

# 3. Rules & Agents Symlinks
mkdir -p "$HOME/.omp/rules" "$HOME/.omp/agent/agents"
for f in "$REPO_DIR"/.omp/rules/*.md; do ln -sf "$f" "$HOME/.omp/rules/$(basename "$f")"; done
for f in "$REPO_DIR"/.omp/agents/*.md; do ln -sf "$f" "$HOME/.omp/agent/agents/$(basename "$f")"; done

# 4. Remote Agent / DB Injection
if [ -f "$RA_DB" ]; then
  echo "💉 Injecting 'omp-mc' provider into remote-agent..."
  NOW=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  sqlite3 "$RA_DB" <<SQL
INSERT OR IGNORE INTO custom_agent_providers (id, name, command, args_json, created_at, updated_at) 
VALUES ('omp-mc-id', 'MaaS Creative / omp-mc', 'omp', '["acp"]', '$NOW', '$NOW');
SQL
fi

# 5. Zshrc Update
if grep -q "$MARKER" "$ZSHRC" 2>/dev/null; then
  sed -i '' "/$MARKER/,/$MARKER_END/d" "$ZSHRC"
fi

EFFECTIVE_MODE="${REMOTE_MODE:-tailscale}"
[ "$EFFECTIVE_MODE" = "tailscale" ] && ! command -v tailscale &>/dev/null && EFFECTIVE_MODE="lan"
case "$EFFECTIVE_MODE" in
  tailscale) RA_FLAGS="--tailscale"; [ "${REMOTE_TAILSCALE_FUNNEL:-false}" = "true" ] && RA_FLAGS="$RA_FLAGS --funnel"; ;;
  lan) RA_FLAGS="--same-lan"; ;;
esac

cat >> "$ZSHRC" <<EOF

$MARKER
# omp-mc configuration
[ -f "$REPO_DIR/models.env" ] && source "$REPO_DIR/models.env"

alias omp-mc='omp'

# Smart remote-agent launcher with auto-kill
unalias omp-mc-remote 2>/dev/null
function omp-mc-remote() {
  local port=\${REMOTE_PORT:-44444}
  local pids=\$(lsof -i tcp:\$port -sTCP:LISTEN -t 2>/dev/null || true)
  
  if [ -n "\$pids" ]; then
    echo "⚠️  Port \$port is occupied by PID(s): \$pids"
    read "ans?   Kill previous session? (y/N): "
    if [[ "\$ans" =~ ^[Yy]$ ]]; then
      echo "💀 Killing processes..."
      echo \$pids | xargs kill -9
      sleep 2
    else
      echo "❌ Aborted."
      return 1
    fi
  fi
  
  npx @kimuson/remote-agent serve ${RA_FLAGS} --port \$port
}

# Update both oh-my-pi and omp-mc configurations
function omp-mc-update() {
  echo "🚀 Updating oh-my-pi binary..."
  omp update
  
  echo "📦 Updating omp-mc rules and configuration..."
  (cd "/Volumes/UNTITLED/Obsidian/MaaS_Creative/2_Software_Product/Other_Projects/omp-mc" && git pull && ./install.sh)
  
  echo "✅ All updates completed!"
}

function omc-init() {
  npx -y npm-add-script -k "audit" -v "cucumber-js && depcruise src && npm audit"
  echo "✅ Audit scripts added to package.json"
}
$MARKER_END
EOF

echo "✅ Setup Complete!"
echo "   🚀マスター設定: $CONFIG_FILE"
echo "   🔄 同期先: $OMP_ENV"
